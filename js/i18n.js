class I18n {
    constructor() {
        this.currentLang = this.getStoredLanguage() || this.detectLanguage();
        this.init();
    }
    
    getStoredLanguage() {
        return localStorage.getItem('ytd-lang');
    }
    
    detectLanguage() {
        const browserLang = navigator.language || navigator.userLanguage;
        return browserLang.startsWith('pt') ? 'pt' : 'en';
    }
    
    init() {
        this.setLanguage(this.currentLang);
        this.setupToggle();
    }
    
    setupToggle() {
        const toggle = document.getElementById('langToggle');
        if (toggle) {
            toggle.addEventListener('click', () => {
                const newLang = this.currentLang === 'pt' ? 'en' : 'pt';
                this.setLanguage(newLang);
            });
        }
    }
    
    setLanguage(lang) {
        this.currentLang = lang;
        localStorage.setItem('ytd-lang', lang);
        document.documentElement.setAttribute('lang', lang === 'pt' ? 'pt-PT' : 'en');
        this.translatePage();
        this.updateLangToggle();
    }
    
    translatePage() {
        // Translate all elements with data-i18n
        document.querySelectorAll('[data-i18n]').forEach(element => {
            const key = element.getAttribute('data-i18n');
            const translation = this.t(key);
            
            if (element.hasAttribute('data-i18n-html')) {
                element.innerHTML = translation;
            } else {
                element.textContent = translation;
            }
        });
        
        // Translate elements with data-i18n-placeholder
        document.querySelectorAll('[data-i18n-placeholder]').forEach(element => {
            const key = element.getAttribute('data-i18n-placeholder');
            element.placeholder = this.t(key);
        });
        
        // Translate elements with data-i18n-aria
        document.querySelectorAll('[data-i18n-aria]').forEach(element => {
            const key = element.getAttribute('data-i18n-aria');
            element.setAttribute('aria-label', this.t(key));
        });
        
        // Translate elements with data-i18n-title
        document.querySelectorAll('[data-i18n-title]').forEach(element => {
            const key = element.getAttribute('data-i18n-title');
            element.title = this.t(key);
        });
        
        // Update document title and meta description
        document.title = this.t('meta.title');
        const metaDesc = document.querySelector('meta[name="description"]');
        if (metaDesc) {
            metaDesc.content = this.t('meta.description');
        }
    }
    
    updateLangToggle() {
        const toggle = document.getElementById('langToggle');
        if (toggle) {
            const ptFlag = toggle.querySelector('.lang-flag-pt');
            const enFlag = toggle.querySelector('.lang-flag-en');
            
            if (this.currentLang === 'pt') {
                if (ptFlag) ptFlag.style.display = 'none';
                if (enFlag) enFlag.style.display = 'block';
            } else {
                if (ptFlag) ptFlag.style.display = 'block';
                if (enFlag) enFlag.style.display = 'none';
            }
        }
    }
    
    t(key) {
        // First, try flat key lookup
        let value = translations[this.currentLang]?.[key];
        
        // If flat lookup succeeded and returned a string, use it
        if (typeof value === 'string') {
            return value;
        }
        
        // Otherwise, try nested path walk for backwards compatibility
        const keys = key.split('.');
        value = translations[this.currentLang];
        
        for (const k of keys) {
            if (value && typeof value === 'object') {
                value = value[k];
            } else {
                break;
            }
        }
        
        // Fallback to English if translation not found
        if (!value && this.currentLang !== 'en') {
            // Try flat lookup in English
            value = translations.en?.[key];
            
            // If flat lookup succeeded and returned a string, use it
            if (typeof value === 'string') {
                return value;
            }
            
            // Otherwise, try nested path walk in English
            value = translations.en;
            for (const k of keys) {
                if (value && typeof value === 'object') {
                    value = value[k];
                } else {
                    break;
                }
            }
        }
        
        return value || key;
    }
}

// Export for use in other scripts
window.I18n = I18n;
